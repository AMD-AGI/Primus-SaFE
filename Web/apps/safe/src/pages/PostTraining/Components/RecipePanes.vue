<template>
  <el-tab-pane :label="`${framework || 'slime'} arguments`" name="args">
    <div class="flex items-center justify-between mb-2">
      <span class="text-[12px] text-[var(--safe-muted)]">
        Read-only. Generated by the same compiler that runs at submit.
      </span>
      <el-button link type="primary" :disabled="!args.length" @click="copyText(command)">
        Copy
      </el-button>
    </div>
    <pre class="pt-recipe-text">{{
      args.length ? command : 'The recipe is not compiled yet.'
    }}</pre>
  </el-tab-pane>
  <el-tab-pane label="Recipe JSON" name="json">
    <div class="flex justify-end mb-2">
      <el-button link type="primary" :disabled="!recipe" @click="copyText(json)">Copy</el-button>
    </div>
    <pre class="pt-recipe-text">{{ json }}</pre>
  </el-tab-pane>
  <el-tab-pane v-for="[name, content] in files" :key="name" :label="name" :name="`file:${name}`">
    <div class="flex justify-end mb-2">
      <el-button link type="primary" @click="copyText(content)">Copy</el-button>
    </div>
    <pre class="pt-recipe-text">{{ content }}</pre>
  </el-tab-pane>
</template>

<script setup lang="ts">
import { computed } from 'vue'
import { formatCommand } from '@/services/postTraining'
import { copyText } from '@/utils/index'

const props = defineProps<{ recipe?: Record<string, unknown>; framework?: string }>()

// COMMANDS is the training entry point of a framework, which its adapter runs with the arguments.
const COMMANDS: Record<string, string> = { slime: 'python3 train.py' }

const args = computed(() => (props.recipe?.frameworkArgs as string[] | undefined) ?? [])
const command = computed(() => formatCommand(args.value, COMMANDS[props.framework || 'slime']))
const json = computed(() => (props.recipe ? JSON.stringify(props.recipe, null, 2) : '—'))
/** The files the recipe writes into the run directory, such as sglang.yaml and plugins.yaml. */
const files = computed(() =>
  Object.entries((props.recipe?.files as Record<string, string> | undefined) ?? {}),
)
</script>

<style scoped>
.pt-recipe-text {
  margin: 0;
  max-height: 600px;
  overflow: auto;
  padding: 12px;
  white-space: pre;
  font-size: 12px;
  line-height: 1.6;
  border: 1px solid var(--safe-border);
  border-radius: 8px;
}
